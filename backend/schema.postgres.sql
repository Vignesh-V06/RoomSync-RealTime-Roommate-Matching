-- RoomSync PostgreSQL schema reference.
-- Apply only to a new, empty PostgreSQL database/schema.
-- Existing MySQL schema.sql is intentionally retained as the MySQL source reference.
-- The live migration target currently uses the "roomsync" schema.

CREATE SCHEMA IF NOT EXISTS roomsync;
SET search_path TO roomsync, public;

DO $$
BEGIN
  CREATE TYPE user_role AS ENUM ('student', 'admin');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
  CREATE TYPE profile_bed_pref AS ENUM ('upper', 'lower');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
  CREATE TYPE room_status AS ENUM ('open', 'closed');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
  CREATE TYPE room_request_status AS ENUM ('applied', 'accepted', 'rejected', 'removed');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  username VARCHAR(40) UNIQUE,
  email VARCHAR(100) NOT NULL UNIQUE,
  phone VARCHAR(30),
  password VARCHAR(255) NOT NULL,
  role user_role DEFAULT 'student',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE IF NOT EXISTS profiles (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  bio TEXT,
  skills VARCHAR(255),
  interests VARCHAR(255),
  academic_details VARCHAR(255),
  language VARCHAR(50),
  branch VARCHAR(50),
  cgpa_range VARCHAR(10),
  bed_pref profile_bed_pref,
  expected_members INTEGER,
  sleep_pref VARCHAR(50),
  study_pref VARCHAR(50),
  food_pref VARCHAR(50),
  cleanliness VARCHAR(50),
  custom_preferences JSONB
);

CREATE TABLE IF NOT EXISTS rooms (
  room_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL UNIQUE REFERENCES users(id),
  block VARCHAR(50) NOT NULL,
  room_number VARCHAR(20),
  room_type VARCHAR(50) NOT NULL,
  bed_type VARCHAR(50) NOT NULL DEFAULT 'Normal Bed',
  total_capacity INTEGER NOT NULL,
  current_occupancy INTEGER DEFAULT 1,
  use_custom_logic BOOLEAN DEFAULT FALSE,
  additional_requirements TEXT,
  custom_options JSONB,
  status room_status NOT NULL DEFAULT 'open',
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_rooms_block_room_number UNIQUE (block, room_number)
);

-- room_id and user_id remain nullable to match the actual MySQL table definition
-- captured during this migration. The application validates both on new requests.
CREATE TABLE IF NOT EXISTS room_requests (
  request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INTEGER REFERENCES rooms(room_id),
  user_id INTEGER REFERENCES users(id),
  status room_request_status DEFAULT 'applied',
  active_user_id INTEGER GENERATED ALWAYS AS (
    CASE WHEN status IN ('applied', 'accepted') THEN user_id ELSE NULL END
  ) STORED,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT room_requests_room_id_user_id_key UNIQUE (room_id, user_id),
  CONSTRAINT uq_room_requests_one_active_per_user UNIQUE (active_user_id)
);

CREATE INDEX IF NOT EXISTS room_requests_user_id_idx ON room_requests(user_id);

CREATE TABLE IF NOT EXISTS registration_otps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(100) NOT NULL,
  name VARCHAR(100) NOT NULL,
  phone VARCHAR(30),
  password_hash VARCHAR(255) NOT NULL,
  otp_hash CHAR(64) NOT NULL,
  request_ip VARCHAR(45),
  attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 255),
  expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  used_at TIMESTAMP WITHOUT TIME ZONE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_registration_otp_email_created
  ON registration_otps(email, created_at);
CREATE INDEX IF NOT EXISTS idx_registration_otp_ip_created
  ON registration_otps(request_ip, created_at);
CREATE INDEX IF NOT EXISTS idx_registration_otp_expiry
  ON registration_otps(expires_at);

CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message TEXT NOT NULL,
  is_read BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS chat_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INTEGER NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
  sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS room_views (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INTEGER NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
  viewer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  view_count BIGINT NOT NULL DEFAULT 1 CHECK (view_count BETWEEN 0 AND 4294967295),
  first_viewed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  last_viewed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_room_views_room_viewer UNIQUE (room_id, viewer_id)
);

CREATE INDEX IF NOT EXISTS idx_room_views_viewer ON room_views(viewer_id);

CREATE TABLE IF NOT EXISTS room_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INTEGER NOT NULL REFERENCES rooms(room_id) ON DELETE CASCADE,
  uploaded_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  original_name VARCHAR(120) NOT NULL,
  mime_type VARCHAR(40) NOT NULL,
  image_data BYTEA NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_room_images_room ON room_images(room_id);

CREATE TABLE IF NOT EXISTS password_reset_otps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  otp_hash CHAR(64) NOT NULL,
  request_ip VARCHAR(45),
  attempts SMALLINT NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 255),
  expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  used_at TIMESTAMP WITHOUT TIME ZONE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_password_reset_user_created
  ON password_reset_otps(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_password_reset_ip_created
  ON password_reset_otps(request_ip, created_at);
CREATE INDEX IF NOT EXISTS idx_password_reset_expiry
  ON password_reset_otps(expires_at);

CREATE TABLE IF NOT EXISTS activity_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  subject_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  event_type VARCHAR(50) NOT NULL,
  entity_type VARCHAR(40),
  entity_id VARCHAR(64),
  metadata JSONB,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_activity_events_type_time
  ON activity_events(event_type, occurred_at);
CREATE INDEX IF NOT EXISTS idx_activity_events_actor_time
  ON activity_events(actor_user_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_activity_events_subject_time
  ON activity_events(subject_user_id, occurred_at);
CREATE INDEX IF NOT EXISTS idx_activity_events_entity
  ON activity_events(entity_type, entity_id);

RESET search_path;
